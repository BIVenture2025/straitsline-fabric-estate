# Cell 3 -- split the DDL into statements. Quote-aware, because a COMMENT "..." string
# can legitimately contain a semicolon; splitting on a bare ";" would cut a statement in
# half. (build_mlv.py also asserts no literal contains one, so this is belt and braces.)
def split_statements(text):
    out, cur, quote = [], [], None
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        if quote:
            cur.append(ch)
            if ch == quote:
                quote = None
            i += 1
        elif ch in ("'", '"'):
            quote = ch
            cur.append(ch)
            i += 1
        elif ch == "-" and i + 1 < n and text[i + 1] == "-":
            while i < n and text[i] != "\n":
                i += 1
        elif ch == ";":
            out.append("".join(cur))
            cur = []
            i += 1
        else:
            cur.append(ch)
            i += 1
    if "".join(cur).strip():
        out.append("".join(cur))
    return [s.strip() for s in out if s.strip()]


