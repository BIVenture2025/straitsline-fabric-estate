    # confident wrong answer to the exact fact SETTLED asks to re-verify.
    stored_raw = ""
    try:
        _sc = spark.sql(f"SHOW CREATE MATERIALIZED LAKE VIEW {view}").collect()
        stored_raw = " ".join(str(v) for r in _sc for v in r.asDict().values())
        row["show_create"] = json.dumps([r.asDict() for r in _sc], default=str)[:8000]
    except Exception as exc:
        row["show_create"] = f"<<failed: {exc}>>"[:500]

    try:
        row["tbl_properties"] = rows_to_text(spark.sql(f"SHOW TBLPROPERTIES {view}"))
    except Exception as exc:
        row["tbl_properties"] = f"<<failed: {exc}>>"[:500]

    # the two presumed P26 facts, answered from the captures above
    # MEASURED S5b, and the first version looked in the wrong place: the xCatalogTableType tag
    # is NOT in SHOW TBLPROPERTIES (0 of 8) but IS in the SHOW CREATE text (8 of 8, value
    # MATERIALIZED_LAKE_VIEW). Checking one channel reported "tag absent" for every view - a
    # false negative on exactly the fact SETTLED asks to re-verify. Both channels now captured.
    props = row.get("tbl_properties", "")
    row["has_xcatalogtabletype"] = "xCatalogTableType" in props          # TBLPROPERTIES channel
    row["has_xcatalog_in_show_create"] = "xCatalogTableType" in stored_raw
    row["xcatalog_value"] = ""
    if row["has_xcatalogtabletype"]:
        try:
            for r in spark.sql(f"SHOW TBLPROPERTIES {view}").collect():
                d = r.asDict()
                if "xCatalogTableType" in str(d.get("key", "")):
                    row["xcatalog_value"] = str(d.get("value", ""))[:200]
        except Exception:
            pass

    submitted = dict(zip(VIEWS, STATEMENTS))[view]
    row["stored_ddl_chars"] = len(stored_raw)
    row["submitted_ddl_chars"] = len(submitted)
    # "verbatim" means the service handed our text back unchanged. Whitespace is normalised
    # out first so the answer is about substance, not formatting. Compared against the RAW
    # capture, never the JSON rendering.
    norm = lambda t: " ".join(t.split()).lower()
    row["stored_ddl_is_verbatim"] = bool(stored_raw) and norm(submitted) in norm(stored_raw)
    capture.append(row)
    print(f"  {view:34s} rows={row['row_count']:>8}  "
          f"tag[showcreate]={row['has_xcatalog_in_show_create']} "
          f"tag[tblprops]={row['has_xcatalogtabletype']}  "
          f"ddl_verbatim={row['stored_ddl_is_verbatim']}")

