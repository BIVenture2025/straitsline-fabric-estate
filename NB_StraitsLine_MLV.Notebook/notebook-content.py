def scalar(sql):
    return spark.sql(sql).collect()[0][0]

assertions = []

def grade(name, expected, actual, tol=0, note=""):
    ok = (actual is not None) and abs(float(actual) - float(expected)) <= tol
    assertions.append({"assertion": name, "expected": float(expected),
                       "actual": None if actual is None else float(actual),
                       "tolerance": float(tol), "passed": bool(ok), "note": note})
    flag = "PASS" if ok else "FAIL"
    print(f"  [{flag}] {name:44s} expected {expected:>14,} actual "
          f"{'None' if actual is None else format(actual, ',')}")
    return ok

