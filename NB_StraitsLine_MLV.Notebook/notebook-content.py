# # NB_StraitsLine_MLV -- Phase 4 Silver + Gold
# 
# Project 30, Fabric E2E Ocean Freight Operations (**StraitsLine**). Creates the eight
# materialized lake views that make up Silver and Gold over `LH_StraitsLine`, then verifies
# them against a T-SQL oracle computed before this DDL existed.
# 
# **All data here is SYNTHETIC and declared as such.** The demurrage tariff is synthetic too,
# and lives in `VL_StraitsLine`.
# 
# ### What it does, in order
# 1. Creates schemas `silver`, `gold` and `audit` if they are absent.
# 2. Runs the eight `CREATE OR REPLACE MATERIALIZED LAKE VIEW` statements, in dependency
#    order (Silver first, then `gold.container_demurrage`, which `gold.voyage_pnl` and
#    `gold.customer_exposure` both read).
# 3. Captures, per view: row count, the service's own stored `SHOW CREATE` text, and the full
#    table-property list.
# 4. Grades 30 assertions against the frozen oracle and writes them to `audit.mlv_assertions`.
# 5. **Writes the audit tables before raising**, so a failed run is readable.
# 
# ### It does NOT refresh
# Learn is explicit: notebooks author materialized lake view definitions, and refresh is
# driven by the lakehouse's own lineage graph and schedules. There is no `REFRESH` statement
# here by design. If the views report 0 rows, open **LH_StraitsLine -> Materialized lake
# views -> Manage** and run the lineage once; that is the supported path.
# 
# ### How to run it (owner)
# Import this file (**Notebook -> Import notebook**), confirm `LH_StraitsLine` is the
# attached lakehouse, and **Run all**. No parameters, no connection string, nothing secret:
